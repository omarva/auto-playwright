package dev.autoplaywright.support;

import com.microsoft.playwright.BrowserContext;
import com.microsoft.playwright.Page;
import com.microsoft.playwright.Tracing;
import com.microsoft.playwright.Video;
import com.microsoft.playwright.assertions.PlaywrightAssertions;
import dev.autoplaywright.config.Config;
import io.cucumber.java.After;
import io.cucumber.java.AfterAll;
import io.cucumber.java.Before;
import io.cucumber.java.BeforeAll;
import io.cucumber.java.Scenario;
import java.io.IOException;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Properties;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/** Scenario lifecycle: isolation, failure evidence (screenshot, trace, video) and cleanup. */
public class Hooks {

  private static final Logger LOG = LoggerFactory.getLogger(Hooks.class);

  private final ScenarioContext ctx;

  public Hooks(ScenarioContext ctx) {
    this.ctx = ctx;
  }

  @BeforeAll
  public static void beforeAll() {
    PlaywrightAssertions.setDefaultAssertionTimeout(Config.timeout());
  }

  @Before(order = 0)
  public void startScenario(Scenario scenario) {
    ctx.start(scenario);
    LOG.info("▶ {} {}", scenario.getName(), scenario.getSourceTagNames());
  }

  @After(order = 0)
  public void finishScenario(Scenario scenario) {
    boolean failed = scenario.isFailed();
    try {
      if (ctx.hasPage()) {
        collectBrowserEvidence(scenario, failed);
      }
    } finally {
      if (ctx.hasApi()) {
        ctx.api().dispose();
      }
      ctx.clear();
      LOG.info("{} {} ({})", failed ? "✘" : "✔", scenario.getName(), scenario.getStatus());
    }
  }

  private void collectBrowserEvidence(Scenario scenario, boolean failed) {
    Page page = ctx.page();
    BrowserContext context = ctx.browserContext();
    try {
      if (Config.screenshot().keep(failed)) {
        try {
          ctx.attachScreenshot(failed ? "Failure screenshot" : "Final screenshot");
        } catch (RuntimeException e) {
          LOG.warn("Could not capture screenshot: {}", e.getMessage());
        }
      }
      if (Config.trace().enabled()) {
        if (Config.trace().keep(failed)) {
          Path trace = ctx.artifactPath("traces", ".zip");
          context.tracing().stop(new Tracing.StopOptions().setPath(trace));
          attachFile(scenario, trace, "application/zip", "Playwright trace");
          ctx.attachText(
              "How to open the trace",
              "text/plain",
              "npx playwright show-trace "
                  + trace
                  + "\nor drop the zip on https://trace.playwright.dev");
        } else {
          context.tracing().stop();
        }
      }
    } finally {
      Video video = page.video();
      context.close();
      if (video != null) {
        if (Config.video().keep(failed)) {
          Path target = ctx.artifactPath("videos", ".webm");
          video.saveAs(target);
          attachFile(scenario, target, "video/webm", "Video");
        }
        video.delete();
      }
    }
  }

  private static void attachFile(Scenario scenario, Path file, String mediaType, String name) {
    try {
      scenario.attach(Files.readAllBytes(file), mediaType, name);
    } catch (IOException e) {
      LOG.warn("Could not attach {}: {}", file, e.getMessage());
    }
  }

  @AfterAll
  public static void afterAll() {
    writeAllureEnvironment();
    BrowserManager.closeAll();
  }

  private static void writeAllureEnvironment() {
    Map<String, String> env = new LinkedHashMap<>();
    env.put("Language", "Java " + Runtime.version().feature());
    env.put(
        "Browser", Config.browser() + Config.browserChannel().map(c -> " (" + c + ")").orElse(""));
    env.put("Browser.Version", BrowserManager.browserVersion());
    env.put("Headless", String.valueOf(Config.headless()));
    env.put("Base.URL", Config.baseUrl());
    env.put("API.Base.URL", Config.apiBaseUrl());
    env.put("Playwright", System.getProperty("playwright.version", "unknown"));
    env.put("OS", System.getProperty("os.name") + " " + System.getProperty("os.arch"));
    env.put("Tags", System.getProperty("cucumber.filter.tags", "not @wip"));

    Properties props = new Properties();
    props.putAll(env);
    Path dir = Config.reportsDir().resolve("allure-results");
    try {
      Files.createDirectories(dir);
      try (OutputStream out = Files.newOutputStream(dir.resolve("environment.properties"))) {
        props.store(out, "Generated by auto-playwright Java");
      }
    } catch (IOException e) {
      LOG.warn("Could not write Allure environment.properties: {}", e.getMessage());
    }
  }
}
